-- 1. إنشاء قاعدة بيانات مدرسة التميز
CREATE DATABASE sspecial_high_school;

-- اختيار قاعدة البيانات
USE special_high_school;


-- 2. إنشاء جدول الطلاب
-- الجنس F أو M
-- المستوى من 1 إلى 6
-- المسار علمي أو انساني
-- المعدل من 100

CREATE TABLE students (
    student_id INT PRIMARY KEY,
    student_name VARCHAR(100),
    birth_date DATE,
    student_gender CHAR(1),
    enrollment_date DATE,
    student_email VARCHAR(100),
    academic_level INT,
    track VARCHAR(20),
    comulative_gpa DECIMAL(5,2)
);


-- 3. إنشاء جدول المعلمين
CREATE TABLE teachers (
    teacher_id INT PRIMARY KEY,
    teacher_name VARCHAR(100),
    birth_date DATE,
    teacher_gender CHAR(1),
    teacher_email VARCHAR(100),
    office_number INT
);


-- 4. إنشاء جدول المواد
CREATE TABLE courses (
    course_id INT PRIMARY KEY,
    course_name VARCHAR(100)
);


